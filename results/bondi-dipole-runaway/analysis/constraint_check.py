#!/usr/bin/env python3
"""Constraint-violation check for the campaign cells.

Einstein's equations carry four constraints that a correct solution must
satisfy at all times.  Numerically they are never exactly zero, and how big
they are -- and whether they shrink when the grid is refined -- is what tells
a reader whether the reported physics is trustworthy.  Two independent stages
are reported, because they fail for different reasons:

1. **Initial data** (``Ham_and_Mom_errors.txt``, written by the elliptic
   solver before the evolution starts).  Percent error per solver iteration;
   the campaign stops the solve at 0.1 %.

2. **Evolution** (``constraint_norms.dat``, written every step and packed
   downsampled).  ``L2_Ham``/``L2_Mom`` are box-averaged violations,
   ``Linf_Ham_amr`` is the worst single point anywhere in the box.

The resolution ladders are the point of the second table: a violation that
is *dominated by discretisation* falls as the grid is refined, while one that
is *inherited from the initial data* does not, because every cell in a ladder
is handed the same solve on the same fixed elliptic grid.  Which of the two
holds decides whether a convergence order is quotable at all, so the script
reports the coarse->fine ratio explicitly rather than leaving it to be eyeballed.

Writes ``analysis/constraint_check.md`` and ``analysis/constraint_check.csv``.
Own module, own output files -- it never touches ``convergence_check.*`` or
``wave_check.*``.  Pure stdlib; cells with no constraint output are skipped, so
it is safe to run at any stage of a campaign.

Usage: constraint_check.py [pack_root]
"""

from __future__ import annotations

import csv
import pathlib
import re
import sys

# Column indices in constraint_norms.dat (0-based), from the header this pack
# injects; see research/bondi_dipole/pack_campaign.sh.
C_TIME, C_L2_HAM, C_L2_MOM, C_LINF_HAM = 0, 1, 2, 15

T_GRID = (0.0, 15.0, 30.0, 45.0, 60.0)
TOL = 1e-6          # a sampled time counts as hit within this of the target
SOLVE_STOP = 0.1    # % -- the elliptic solver's exit tolerance

# A ladder is the same physics on several grids.  Key = cell name with the
# trailing resolution stripped; the ladder table only prints groups of >= 2.
LADDER_RE = re.compile(r"_n(\d+)$")


def rows_of(path: pathlib.Path) -> list[list[float]]:
    out: list[list[float]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        try:
            out.append([float(x) for x in line.split()])
        except ValueError:      # stray text header without a '#'
            continue
    if not out:
        return out
    width = max(len(r) for r in out)
    return [r for r in out if len(r) == width]


def nearest(rows: list[list[float]], t: float, col: int) -> float | None:
    """Value at the sampled time closest to t, or None if the run never got
    there.  No interpolation: these are monotone-ish noisy norms and a reader
    comparing cells wants the number the code actually wrote."""
    if not rows or col >= len(rows[0]):
        return None
    best = min(rows, key=lambda r: abs(r[C_TIME] - t))
    # Runs stop at different times; do not invent a value past the end.
    if best[C_TIME] < t - 0.5 - TOL:
        return None
    return best[col]


def solve_history(path: pathlib.Path) -> list[tuple[int, float, float]]:
    """(iteration, Ham error %, Mom error %) from the elliptic solver log."""
    out: list[tuple[int, float, float]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        try:
            out.append((int(parts[0]), float(parts[1]), float(parts[2])))
        except ValueError:      # the header line
            continue
    return out


def fmt(v: float | None, spec: str = ".3e") -> str:
    return "—" if v is None else format(v, spec)


def main(argv: list[str]) -> int:
    pack = pathlib.Path(argv[0]) if argv else pathlib.Path(__file__).resolve().parent.parent
    camp = pack / "campaign"
    if not camp.is_dir():
        print("[constraints] no campaign/ directory -- nothing to check")
        return 0

    md = [
        "# Constraint-violation check",
        "",
        "How well each cell satisfies Einstein's constraint equations, at the two",
        "stages where it can go wrong independently: the elliptic solve that builds",
        "the initial data, and the evolution that follows.  Regenerated by",
        "`analysis/constraint_check.py` via `research/bondi_dipole/pack_campaign.sh`.",
        "",
        "## Initial data — elliptic solve",
        "",
        f"Percent error per solver iteration; the solve stops below {SOLVE_STOP} %.",
        "",
        "| cell | iterations | Ham start → final | Mom start → final | met tolerance |",
        "|---|---|---|---|---|",
    ]
    csv_rows: list[dict] = []
    solved: dict[str, tuple[float, float]] = {}

    for cell in sorted(camp.iterdir()):
        f = cell / "Ham_and_Mom_errors.txt"
        if not f.is_file():
            continue
        hist = solve_history(f)
        if not hist:
            continue
        n, h0, m0 = hist[0]
        n_last, h, m = hist[-1]
        ok = max(h, m) <= SOLVE_STOP
        solved[cell.name] = (h, m)
        md.append(f"| {cell.name} | {n_last} | {h0:.2f} → {h:.4f} | "
                  f"{m0:.2f} → {m:.4f} | {'yes' if ok else 'still solving'} |")
        csv_rows.append({"cell": cell.name, "stage": "initial_data", "time": "",
                         "L2_Ham": f"{h:.6e}", "L2_Mom": f"{m:.6e}", "Linf_Ham": "",
                         "note": f"percent; {n_last} iterations"})

    md += [
        "",
        "## Evolution — constraint norms over time",
        "",
        "`L2_Ham`/`L2_Mom` are averaged over the whole box; `Linf_Ham` is the worst",
        "single point.  Read down a column to see growth in time.",
        "",
        "| cell | t | L2_Ham | L2_Mom | Linf_Ham |",
        "|---|---|---|---|---|",
    ]

    ladders: dict[str, dict[int, list[list[float]]]] = {}
    for cell in sorted(camp.iterdir()):
        f = cell / "constraint_norms.dat"
        if not f.is_file():
            continue
        rows = rows_of(f)
        if not rows:
            continue
        m = LADDER_RE.search(cell.name)
        if m:
            ladders.setdefault(cell.name[: m.start()], {})[int(m.group(1))] = rows
        for t in T_GRID:
            ham = nearest(rows, t, C_L2_HAM)
            mom = nearest(rows, t, C_L2_MOM)
            linf = nearest(rows, t, C_LINF_HAM)
            if ham is None:
                continue
            md.append(f"| {cell.name} | {t:g} | {fmt(ham)} | {fmt(mom)} | {fmt(linf)} |")
            csv_rows.append({"cell": cell.name, "stage": "evolution", "time": f"{t:g}",
                             "L2_Ham": fmt(ham, ".6e"), "L2_Mom": fmt(mom, ".6e"),
                             "Linf_Ham": fmt(linf, ".6e"), "note": ""})

    # Does refining the grid reduce the violation?  Coarsest / finest at each
    # sampled time.  Ratio ~ 1 means the violation is inherited from the shared
    # initial-data solve and no convergence order can be extracted from it.
    ladder_md = [
        "",
        "## Does refining the grid reduce the violation?",
        "",
        "Coarsest grid ÷ finest grid, same physics.  A violation set by the grid",
        "shrinks as the grid is refined, giving a ratio well above 1.  A ratio near 1",
        "means the violation is inherited from somewhere the grid does not control —",
        "here the elliptic solve, which every cell of a ladder shares unchanged.",
        "",
        "| ladder | grids | t | L2_Ham coarse ÷ fine | Linf_Ham coarse ÷ fine |",
        "|---|---|---|---|---|",
    ]
    any_ladder = False
    for base, by_n in sorted(ladders.items()):
        if len(by_n) < 2:
            continue
        any_ladder = True
        ns = sorted(by_n)
        lo, hi = by_n[ns[0]], by_n[ns[-1]]
        grids = ", ".join(str(n) for n in ns)
        for t in T_GRID:
            a_h, b_h = nearest(lo, t, C_L2_HAM), nearest(hi, t, C_L2_HAM)
            a_l, b_l = nearest(lo, t, C_LINF_HAM), nearest(hi, t, C_LINF_HAM)
            if a_h is None or b_h is None:
                continue
            r_h = a_h / b_h if b_h else float("nan")
            r_l = a_l / b_l if (a_l is not None and b_l) else float("nan")
            ladder_md.append(f"| {base} | {grids} | {t:g} | {r_h:.2f}× | {r_l:.2f}× |")
            csv_rows.append({"cell": base, "stage": "ladder_ratio", "time": f"{t:g}",
                             "L2_Ham": f"{r_h:.4f}", "L2_Mom": "",
                             "Linf_Ham": f"{r_l:.4f}",
                             "note": f"coarse n{ns[0]} / fine n{ns[-1]}"})
    if any_ladder:
        md += ladder_md

    if not csv_rows:
        print("[constraints] no constraint output packed -- nothing to check")
        return 0

    (pack / "analysis" / "constraint_check.md").write_text("\n".join(md) + "\n",
                                                           encoding="utf-8")
    with (pack / "analysis" / "constraint_check.csv").open(
            "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["cell", "stage", "time", "L2_Ham",
                                           "L2_Mom", "Linf_Ham", "note"])
        w.writeheader()
        w.writerows(csv_rows)
    print(f"[constraints] wrote constraint_check.csv ({len(csv_rows)} rows) "
          "and constraint_check.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
