#!/usr/bin/env python3
"""Track a same-sign pair's two lumps from the chi z-slice cache.

Same-sign pairs put both stars in one sector, so the sector splitter reports a
single barycentre and no separation -- the per-star measurement has to come
from the fields themselves.  This reads the cached ``chi_minus_1`` z-slices a
run wrote with ``--frames-cache-slices``, y-averages |chi-1| into a profile
along x, and follows its two strongest local maxima.  Those maxima are the
stars: wells for a canonical (PP) pair, hills for a phantom (MM) one, which is
why the absolute value is taken and the same script serves both.

The gap goes to zero when the profile stops having two maxima -- that is the
merger, and the time it happens is the number the paper quotes.

    track_wells.py <run>/frames <out.dat> [--label "MM pair, N128"]
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

import numpy as np

INDEX_RE = re.compile(r"(\d+)\.npz$")
# Below this the profile is flat noise and "maxima" are meaningless.
MIN_PEAK = 1e-6


def profile(npz: pathlib.Path) -> tuple[np.ndarray, np.ndarray]:
    """y-averaged |chi-1| along x, with the x coordinates it lives on."""
    d = np.load(npz, allow_pickle=True)
    arr = np.abs(np.asarray(d["arr"], dtype=float))
    x0, x1 = float(d["extent"][0]), float(d["extent"][1])
    prof = np.nanmean(arr, axis=0)
    return np.linspace(x0, x1, prof.size), prof


def two_maxima(x: np.ndarray, prof: np.ndarray) -> tuple[float, float]:
    """The two strongest interior local maxima, ordered; (nan, nan) if fewer."""
    interior = np.arange(1, prof.size - 1)
    peaks = interior[(prof[1:-1] > prof[:-2]) & (prof[1:-1] > prof[2:])]
    peaks = peaks[prof[peaks] > MIN_PEAK]
    if peaks.size < 2:
        return float("nan"), float("nan")
    best = peaks[np.argsort(prof[peaks])[-2:]]
    a, b = sorted(x[i] for i in best)
    return a, b


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("frames_dir")
    ap.add_argument("out")
    ap.add_argument("--label", default="pair")
    ap.add_argument("--series", default="chi_minus_1_z")
    args = ap.parse_args(argv)

    cache = pathlib.Path(args.frames_dir) / "_slice_cache" / args.series
    if not cache.is_dir():
        print(f"[wells] no slice cache at {cache}", file=sys.stderr)
        return 1

    rows = []
    for f in sorted(cache.glob("*.npz"), key=lambda p: int(INDEX_RE.search(p.name).group(1))):
        d = np.load(f, allow_pickle=True)
        t = float(d["time"])
        x, prof = profile(f)
        a, b = two_maxima(x, prof)
        gap = b - a if np.isfinite(a) else 0.0
        rows.append((t, a, b, gap, float(np.nanmax(prof))))

    merged = next((t for t, a, *_ in rows if not np.isfinite(a)), None)
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as fh:
        fh.write(f"# Two-lump tracking of the {args.label}, derived from the\n")
        fh.write(f"# {args.series} z-slice cache (y-averaged |chi-1| profile; the two\n")
        fh.write("# strongest local maxima are the stars; gap = 0 once they have merged).\n")
        fh.write(f"# Generated by analysis/track_wells.py.  Merger (profile loses its\n")
        fh.write(f"# second maximum) at t = {merged if merged is not None else float('nan')}.\n")
        fh.write("# time  x_lump_1  x_lump_2  gap  peak_abs_chi_minus_1\n")
        for t, a, b, gap, pk in rows:
            fh.write(f"{t:10.4f} {a:9.3f} {b:9.3f} {gap:8.3f}  {pk:.4e}\n")
    print(f"[wells] {len(rows)} frames -> {out}")
    print(f"[wells] first frame with a single lump: t = {merged}")
    if rows:
        print(f"[wells] initial gap {rows[0][3]:.3f} at t = {rows[0][0]:.1f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
