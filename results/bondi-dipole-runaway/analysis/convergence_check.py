#!/usr/bin/env python3
"""Cross-resolution check for the uniform-grid convergence campaign.

Reads ``campaign/convA_*_n<N>/sector_barycenters.dat`` (whatever resolutions
are packed so far), interpolates every series onto common times, and tabulates
the three quantities the paper's error bars rest on:

* pair drift   — centre-of-pair displacement in the mixed cell (the effect);
* gap          — canonical-minus-phantom separation in the mixed cell;
* control drift — canonical displacement in the two-positive cell (the
  numerical artefact, which must shrink as resolution rises).

Writes ``analysis/convergence_check.csv`` (long format: one row per group /
quantity / time / resolution) and ``analysis/convergence_check.md`` (wide
tables with the max spread across resolutions).  Pure stdlib; groups or
resolutions that are not packed yet are simply absent from the output, so the
script is safe to run at any point of the campaign.

Usage: convergence_check.py [pack_root]
"""

from __future__ import annotations

import csv
import math
import pathlib
import re
import sys

CENTER = 32.0          # convA cells: L = 64 box, stars seeded around x = 32
T_REF = (15.0, 20.0)   # fixed reference times quoted in the write-ups

# group label -> campaign cell prefix (resolution suffix n<N> is discovered)
GROUPS = (
    ("runaway pair (pm)", "convA_pm_n"),
    ("equal-mass pair (pm_eqm)", "convA_pm_eqm_n"),
    ("control (pp)", "convA_pp_n"),
)


def read_series(path: pathlib.Path) -> list[tuple[float, float, float]]:
    """(t, bary_x_canon, bary_x_phantom) rows; phantom may be NaN (pp cells)."""
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        f = line.split()
        rows.append((float(f[0]), float(f[2]), float(f[7])))
    return rows


def interp(rows: list[tuple[float, float, float]], t: float, col: int) -> float:
    if not rows or t < rows[0][0] or t > rows[-1][0]:
        return math.nan
    for i in range(1, len(rows)):
        if rows[i][0] >= t:
            t0, t1 = rows[i - 1][0], rows[i][0]
            v0, v1 = rows[i - 1][col], rows[i][col]
            w = 0.0 if t1 == t0 else (t - t0) / (t1 - t0)
            return v0 + w * (v1 - v0)
    return math.nan


def quantities(prefix: str, rows) -> dict[str, float | None]:
    del prefix  # same recipe for every group; kept for signature clarity
    def at(t):
        c = interp(rows, t, 1)
        p = interp(rows, t, 2)
        out = {}
        if not math.isnan(p):  # mixed cell: pair drift + gap
            out["pair drift"] = 0.5 * (c + p) - CENTER
            out["gap"] = c - p
        else:                  # control cell: canonical drift = the artefact
            out["control drift"] = c - CENTER
        return out
    return at


def main(argv: list[str]) -> int:
    pack = pathlib.Path(argv[0]) if argv else pathlib.Path(__file__).resolve().parent.parent
    camp = pack / "campaign"
    out_csv = pack / "analysis" / "convergence_check.csv"
    out_md = pack / "analysis" / "convergence_check.md"

    long_rows: list[dict] = []
    md: list[str] = [
        "# Cross-resolution check (uniform-grid campaign)",
        "",
        "Same physics on progressively finer grids.  A real effect barely",
        "moves between rows of increasing resolution; a numerical artefact",
        "shrinks.  Spread = max pairwise difference as % of the finest-grid",
        "value.  Regenerated by `analysis/convergence_check.py` via",
        "`research/bondi_dipole/pack_campaign.sh`.",
    ]

    for label, prefix in GROUPS:
        cells = sorted(
            (int(re.search(r"n(\d+)$", d.name).group(1)), d)
            for d in camp.glob(f"{prefix}[0-9]*")
            if (d / "sector_barycenters.dat").is_file()
        )
        if len(cells) < 2:
            continue
        series = {n: read_series(d / "sector_barycenters.dat") for n, d in cells}
        t_common = min(rows[-1][0] for rows in series.values())
        times = [t for t in T_REF if t <= t_common]
        t_last = math.floor(t_common * 2) / 2
        if t_last > (times[-1] if times else 0):
            times.append(t_last)

        res = sorted(series)
        md += ["", f"## {label} — N = {', '.join(str(n) for n in res)}", ""]
        header = ["quantity", "t"] + [f"N={n}" for n in res] + ["spread"]
        md += ["| " + " | ".join(header) + " |",
               "|" + "---|" * len(header)]

        for t in times:
            per_res = {n: quantities(prefix, series[n])(t) for n in res}
            for q in per_res[res[0]]:
                vals = [per_res[n][q] for n in res]
                finest = vals[-1]
                spread = (max(vals) - min(vals)) / abs(finest) * 100 if finest else math.nan
                for n, v in zip(res, vals):
                    long_rows.append({"group": label, "quantity": q, "t": t,
                                      "resolution": n, "value": f"{v:.6f}"})
                cells_txt = [f"{v:+.5f}" for v in vals]
                md.append(f"| {q} | {t:g} | " + " | ".join(cells_txt)
                          + f" | {spread:.1f}% |")

    if not long_rows:
        print("[convergence] fewer than two resolutions packed -- nothing to check")
        return 0

    with out_csv.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["group", "quantity", "t", "resolution", "value"])
        w.writeheader()
        w.writerows(long_rows)
    out_md.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"[convergence] wrote {out_csv.name} ({len(long_rows)} rows) and {out_md.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
