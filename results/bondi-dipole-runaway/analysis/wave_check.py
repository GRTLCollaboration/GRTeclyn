#!/usr/bin/env python3
"""Gravitational-wave extraction check for the campaign cells.

The double-size-box cells exist to measure radiation on shells that sit well
outside the matter.  This script answers the only question that decides whether
a wave amplitude is quotable: does ``r * psi4`` agree across the extraction
radii once each shell is read at its own RETARDED time ``u = t - r``?

* agreement  -> the shells see one outgoing 1/r wave: the amplitude is physical;
* divergence -> the shells see different things: near-zone gauge, junk from the
  initial data, or matter that has expanded onto the shells.  Not quotable.

A second table reports when the matter reaches the shells, which is what ends
the usable window here.

Writes ``analysis/wave_check.md`` and ``analysis/wave_check.csv``.  Own module,
own output files -- it never touches ``convergence_check.*``.  Pure stdlib;
cells without psi4 output are skipped, so it is safe at any campaign stage.

Usage: wave_check.py [pack_root]
"""

from __future__ import annotations

import csv
import math
import pathlib
import re
import sys

CLEAN = 1.5   # max/min of r*psi4 across shells still counted as "one wave"
U_GRID = (5.0, 10.0, 15.0, 20.0, 25.0, 30.0, 35.0, 40.0, 45.0)


def radii_of(path: pathlib.Path) -> list[float]:
    """Shell radii in column order.  Each shell appears twice in the header
    (Re and Im), so de-duplicate while keeping the order."""
    header = path.read_text(encoding="utf-8").split("\n")[0]
    seen: list[float] = []
    for r in re.findall(r"R=([0-9.]+)", header):
        val = float(r)
        if val not in seen:
            seen.append(val)
    return seen


def rows_of(path: pathlib.Path) -> list[list[float]]:
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        try:
            out.append([float(x) for x in line.split()])
        except ValueError:      # stray text header without a '#'
            continue
    if not out:
        return out
    width = max(len(r) for r in out)
    return [r for r in out if len(r) == width]


def interp(rows: list[list[float]], t: float, col: int) -> float:
    if not rows or t < rows[0][0] or t > rows[-1][0]:
        return math.nan
    for i in range(1, len(rows)):
        if rows[i][0] >= t:
            t0, t1 = rows[i - 1][0], rows[i][0]
            w = 0.0 if t1 == t0 else (t - t0) / (t1 - t0)
            return rows[i - 1][col] + w * (rows[i][col] - rows[i - 1][col])
    return math.nan


def amplitude(rows, i_radius: int, t: float) -> float:
    """|psi4| of the l=2, m=0 mode at shell i_radius, coordinate time t."""
    re_ = interp(rows, t, 1 + 2 * i_radius)
    im_ = interp(rows, t, 2 + 2 * i_radius)
    return math.hypot(re_, im_)


def matter_reach(cell: pathlib.Path) -> list[tuple[float, float]]:
    """(t, rms radius of the canonical sector) -- how far the matter has spread."""
    f = cell / "sector_barycenters.dat"
    if not f.is_file():
        return []
    return [(r[0], r[5]) for r in rows_of(f)]


def main(argv: list[str]) -> int:
    pack = pathlib.Path(argv[0]) if argv else pathlib.Path(__file__).resolve().parent.parent
    camp = pack / "campaign"

    md = [
        "# Gravitational-wave extraction check",
        "",
        "`r × Ψ₄` for the l = 2, m = 0 mode, each shell read at its own retarded",
        f"time `u = t − r`.  One outgoing wave gives the same value on every shell;",
        f"the spread column is max/min across shells, and ≤ {CLEAN}× is counted as clean.",
        "Regenerated by `analysis/wave_check.py` via",
        "`research/bondi_dipole/pack_campaign.sh`.",
    ]
    long_rows: list[dict] = []

    for cell in sorted(camp.iterdir()):
        f = cell / "psi4_mode_l2m0.dat"
        if not f.is_file():
            continue
        radii = radii_of(f)
        if len(radii) < 2:
            continue
        rows = rows_of(f)
        if not rows:
            continue
        t_end = rows[-1][0]

        md += ["", f"## {cell.name} — shells at r = {', '.join(f'{r:g}' for r in radii)}", ""]
        md += ["| u = t − r | " + " | ".join(f"r={r:g}" for r in radii) + " | spread | |",
               "|" + "---|" * (len(radii) + 3)]

        marks: list[tuple[float, bool]] = []   # (u, clean?) in order
        for u in U_GRID:
            vals = []
            for i, r in enumerate(radii):
                t = u + r
                vals.append(amplitude(rows, i, t) * r if t <= t_end else math.nan)
            good = [v for v in vals if v == v and v > 0]
            if len(good) < 2:
                continue
            spread = max(good) / min(good)
            ok = spread <= CLEAN
            marks.append((u, ok))
            for r, v in zip(radii, vals):
                long_rows.append({"cell": cell.name, "u": u, "radius": r,
                                  "r_psi4": "" if v != v else f"{v:.6e}"})
            md.append(f"| {u:g} | " + " | ".join("—" if v != v else f"{v:.3e}" for v in vals)
                      + f" | {spread:.1f}× | {'clean' if ok else 'contaminated'} |")

        reach = matter_reach(cell)
        note = ""
        if reach:
            inner = min(radii)
            hit = next((t for t, rms in reach if rms >= inner), None)
            note = (f"  Matter (rms radius of the canonical sector) reaches the innermost "
                    f"shell r = {inner:g} at t ≈ {hit:.0f}." if hit else
                    "  The matter never reaches the innermost shell.")
        # A single clean row proves nothing -- shells can agree by accident while
        # crossing.  Report the longest CONTIGUOUS clean stretch, and only if it
        # spans at least two sampled retarded times.
        best: tuple[float, float] | None = None
        run: list[float] = []
        for u, ok in marks + [(math.nan, False)]:
            if ok:
                run.append(u)
                continue
            if len(run) >= 2 and (best is None or run[-1] - run[0] > best[1] - best[0]):
                best = (run[0], run[-1])
            run = []
        verdict = (f"**Usable window: u = {best[0]:g} … {best[1]:g}.**" if best
                   else "**No usable window: the shells never agree on one wave for "
                        "two consecutive samples.**")
        md += ["", verdict + note]

    if not long_rows:
        print("[waves] no psi4 output packed -- nothing to check")
        return 0

    (pack / "analysis" / "wave_check.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    with (pack / "analysis" / "wave_check.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["cell", "u", "radius", "r_psi4"])
        w.writeheader()
        w.writerows(long_rows)
    print(f"[waves] wrote wave_check.csv ({len(long_rows)} rows) and wave_check.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
